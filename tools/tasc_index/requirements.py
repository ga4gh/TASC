"""Technical product requirements table, generated from ``requirements/requirements.json``.

Each requirement names the documents (ADRs, recommendations, governance) and registries that
define it. Status and date are read from those documents via the index, so the table cannot
drift from them. The date is the latest date among the referenced documents and is never set on
a requirement; it is blank when there is no document, so add the date to the source instead.
A requirement may override the status, which is needed when it has no TASC document (for
example one that comes from the PDAP).
"""

from __future__ import annotations

import json
import os
from dataclasses import dataclass
from pathlib import Path, PurePosixPath
from urllib.parse import quote

from tasc_index.markdown import cell, table

ACCEPTED_STATUSES = {"Accepted", "Approved"}
REQUIRED_FIELDS = ("name", "category", "details", "applies")
REQUIREMENTS_NOTICE = (
    "<!-- Generated by tools/tasc_index/requirements.py from requirements/requirements.json "
    "and the index files. Do not edit by hand: change requirements.json or the source "
    "document and the workflow will regenerate this. -->"
)
HEADER = ["Requirement name", "Requirement details", "When it applies in PDAP", "Status",
          "Documentation", "Date of approval"]  # fmt: skip


@dataclass(frozen=True)
class Category:
    slug: str
    title: str


# The order here is the order of the sections in the generated page.
CATEGORIES = [
    Category("repository-website", "Repository and website"),
    Category("starter-kit-conformance", "Starter kit and conformance"),
    Category("specification-design", "Specification design"),
    Category("registration", "Registration in TASC registries"),
    Category("citation", "Citation"),
    Category("ownership", "Ownership"),
]


def load_requirements(path: Path) -> list[dict]:
    return json.loads(path.read_text(encoding="utf-8"))["requirements"]


def validate_requirements(
    requirements: list[dict], documents: dict[str, dict], registries: dict[str, dict]
) -> list[str]:
    errors: list[str] = []
    categories = {c.slug for c in CATEGORIES}
    seen: set[str] = set()
    for r in requirements:
        label = r.get("name") or "<unnamed requirement>"
        if "date" in r:
            errors.append(f"{label}: 'date' is not allowed; it comes from the referenced documents")
        errors += [f"{label}: missing '{f}'" for f in REQUIRED_FIELDS if not r.get(f)]
        if r.get("category") and r["category"] not in categories:
            errors.append(f"{label}: category '{r['category']}' is not one of {sorted(categories)}")
        if label in seen:
            errors.append(f"{label}: duplicate requirement name")
        seen.add(label)
        errors += [
            f"{label}: unknown document '{d}'" for d in r.get("documents", []) if d not in documents
        ]
        errors += [
            f"{label}: unknown registry '{s}'"
            for s in r.get("registries", [])
            if s not in registries
        ]
        cited = r.get("documents") or r.get("registries") or r.get("references")
        if not cited:
            errors.append(f"{label}: cites no document, registry or reference")
        if not r.get("documents") and not r.get("status"):
            errors.append(f"{label}: has no document to take a status from, so it needs 'status'")
    return errors


def derived_status(docs: list[dict]) -> str:
    if all(d["status"] in ACCEPTED_STATUSES for d in docs):
        return "Approved"
    return "Draft ADR" if any(d["id"].startswith("TASC-ADR-") for d in docs) else "Draft"


def rel_link(label: str, path: str, from_dir: str) -> str:
    rel = PurePosixPath(os.path.relpath(path, from_dir))
    return f"[{cell(label)}]({quote(rel.as_posix())})"


def render_requirements_readme(
    requirements: list[dict], documents: list[dict], registries: list[dict]
) -> str:
    by_id = {d["id"]: d for d in documents}
    by_slug = {r["slug"]: r for r in registries}

    def row(r: dict) -> list[str]:
        docs = [by_id[i] for i in r.get("documents", [])]
        status = r.get("status") or derived_status(docs)
        date = max((d["date"] for d in docs), default="")
        citations = [rel_link(d["id"], d["path"], "requirements") for d in docs]
        for slug in r.get("registries", []):
            citations.append(rel_link(f"{slug}/", by_slug[slug]["path"], "requirements"))
        citations += [cell(x) for x in r.get("references", [])]
        cells = [cell(c) for c in (r["name"], r["details"], r["applies"], status)]
        cells += ["; ".join(citations), date]
        return cells

    out = [
        "# GA4GH Technical Product Requirements\n",
        f"{REQUIREMENTS_NOTICE}\n",
        '"When it applies" distinguishes a requirement that must be met to reach approval '
        "from one that continues for the life of the product. Status and date are taken from "
        "the documents listed against each requirement.\n",
    ]
    for number, category in enumerate(CATEGORIES, start=1):
        rows = [row(r) for r in requirements if r["category"] == category.slug]
        if not rows:
            continue
        out.append(f"## {number}. {category.title}\n")
        out.append(table(HEADER, rows))
        out.append("")
    return "\n".join(out)
